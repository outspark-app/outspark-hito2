from typing import Protocol


class Profiles(Protocol):
    def actor(self, actor: str) -> dict: ...


class Connections(Protocol):
    def contacts(self, actor: str, budget) -> list[str]: ...
    def active_guard(self, actor: str, other: str): ...


class Communities(Protocol):
    def memberships(self, actor: str, budget) -> list[str]: ...
    def catalog(self, budget) -> list[str]: ...
    def membership_guard(self, actor: str, community: str): ...


class Publishing(Protocol):
    def original(self, publication_id: str) -> dict: ...
    def originals(self, ids: list[str], budget) -> tuple[dict, int]: ...
    def activity(self, actor: str, limit: int, budget) -> list[dict]: ...
    def community_roots(self, community: str, limit: int, budget) -> list[dict]: ...
    def provenance(self, publication_id: str, sources: list[str], budget=None) -> dict: ...
    def active_guard(self, publication_id: str): ...
