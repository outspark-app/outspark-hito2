from typing import Protocol


class DatasetSource(Protocol):
    metadata: dict

    def node_ids(self) -> list[int]: ...


class ImportRepository(Protocol):
    def preview(self, source: DatasetSource) -> dict: ...
    def begin(self, metadata: dict, resume: bool = False) -> dict: ...
    def write(self, source: DatasetSource) -> dict: ...
    def verify(self, dataset_id: str, expected: dict, files: dict) -> dict: ...
    def finish(
        self, metadata: dict, inventory: dict, verification: dict, profiles: dict
    ) -> dict: ...
