from typing import Protocol


class DatasetsRepository(Protocol):
    def manifest(self, dataset_id: str) -> dict | None: ...
    def node(self, dataset_id: str, node_id: int) -> dict | None: ...
    def nodes(self, dataset_id: str, limit: int, cursor: str | None) -> dict: ...
    def records(
        self, dataset_id: str, node_id: int, kind: str, limit: int, cursor: str | None
    ) -> dict: ...
    def neighbors_many(self, dataset_id: str, nodes: list[int], budget: dict) -> dict: ...
