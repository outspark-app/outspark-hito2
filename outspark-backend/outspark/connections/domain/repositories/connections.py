from typing import Protocol


class ConnectionsRepository(Protocol):
    def contacts(self, actor: str, limit: int, cursor: str | None) -> dict: ...
    def contact_window(self, actor: str, budget) -> list[str]: ...
    def friendship_states(self, actor: str, other: str) -> list[str]: ...
    def remove(self, friendship, actor: str, guards: tuple) -> None: ...
