from typing import Protocol

from ..model.aggregates import Preferences


class ProfilesRepository(Protocol):
    def profile(self, user_id: str) -> dict | None: ...
    def preferences(self, user_id: str) -> dict: ...
    def save_preferences(self, preferences: Preferences, guards: tuple) -> dict: ...
    def provision_imported(self, users: list[dict], source: str) -> dict: ...
