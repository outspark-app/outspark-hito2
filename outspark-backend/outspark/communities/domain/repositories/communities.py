from typing import Protocol


class CommunitiesRepository(Protocol):
    def community(self, community: str) -> dict | None: ...
    def topic_exists(self, topic: str) -> bool: ...
    def member(self, actor: str, community: str) -> bool: ...
    def catalog(self, kind: str, limit: int, cursor: str | None) -> dict: ...
    def memberships(self, actor: str, limit: int, cursor: str | None) -> dict: ...
    def member_window(self, actor: str, budget) -> list[str]: ...
    def catalog_window(self, budget) -> list[str]: ...
    def membership_states(self, actor: str, community: str) -> list[str]: ...
    def save_membership(
        self, membership, states: list[str], instant: str, guards: tuple
    ) -> None: ...
