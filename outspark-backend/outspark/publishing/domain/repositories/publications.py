from typing import Protocol

from ..model.aggregates import PublicationDraft


class PublicationsRepository(Protocol):
    def original(self, publication_id: str) -> dict | None: ...
    def event(self, reference: str) -> dict | None: ...
    def participated(self, publication_id: str, actor: str) -> bool: ...
    def replay(self, actor: str, key: str, payload: dict) -> dict | None: ...
    def publish(
        self, draft: PublicationDraft, key: str, payload: dict, instant: str, guards: tuple
    ) -> dict: ...
    def repost(
        self, actor: str, parent: dict, key: str, payload: dict, instant: str, guards: tuple
    ) -> dict: ...
    def comment(
        self,
        actor: str,
        publication_id: str,
        body: str,
        key: str,
        payload: dict,
        instant: str,
        guards: tuple,
    ) -> dict: ...
    def retire(self, publication_id: str, guards: tuple) -> None: ...
    def own_originals(self, actor: str, limit: int, cursor: str | None) -> dict: ...
    def comments(self, publication_id: str, limit: int, cursor: str | None) -> dict: ...
    def events(self, publication_id: str, budget=None) -> list[dict]: ...
    def originals(self, ids: list[str], budget) -> tuple[dict, int]: ...
    def activity(self, actor: str, limit: int, budget) -> list[dict]: ...
    def community_roots(self, community: str, limit: int, budget) -> list[dict]: ...
